import { api } from '@/lib/api';
import { useScanStore } from '@/lib/scanStore';
import { usePortfolioStore } from '@/lib/portfolioStore';
import { useSettingsStore, DEFAULT_CONFIDENCE_GATE } from '@/lib/settingsStore';
import { runStockScanWithContinuation, isStockManualScanCurrent } from '@/lib/stockScan';
import * as execution from '@/lib/stockExecutionSession';
import type { PositionCardData, StockScanResult } from '@/types/stockDomain';
jest.mock('@/lib/api', () => ({ api: { postStockScan: jest.fn(), getLastStockScanStatus: jest.fn().mockResolvedValue({ status: 'idle' }) } }));
const candidate = (symbol: string, status = 'PASS') => ({ symbol, direction: 'Bullish', shares: 30, stock_status: status, strategy: { entry_price: 150, stop_price: 145, target_price: 160, targets: [160, 165] } } as PositionCardData);
const result = (id: string, candidates: PositionCardData[] = []) => ({ scan_id: id, timestamp: 't', candidates, rejected: [] } as unknown as StockScanResult);
const deferred = <T,>() => { let resolve!: (value: T) => void; let reject!: (error: Error) => void; const promise = new Promise<T>((r, j) => { resolve = r; reject = j; }); return { promise, resolve, reject }; };
const realAdd = usePortfolioStore.getState().addPosition;
beforeEach(() => {
  jest.restoreAllMocks(); jest.clearAllMocks();
  useScanStore.setState({ context: { universe: 'SP500', direction: 'Bullish', horizon: 'Swing' } as never, stockScanResult: null, scanState: 'IDLE', stockScanError: null, stockAfterScanIntent: {}, stockAfterScanOutcomes: {}, stockScanFeedback: { error: null, notice: null } });
  usePortfolioStore.setState({ addPosition: realAdd });
  useSettingsStore.setState({ confidenceGate: { ...DEFAULT_CONFIDENCE_GATE } });
});
afterEach(() => usePortfolioStore.setState({ addPosition: realAdd }));
it.each(['success', 'failure'])('returns obsolete for deferred old %s while newer run remains scanning', async oldOutcome => {
  const old = deferred<StockScanResult>();
  (api.postStockScan as jest.Mock).mockReturnValueOnce(old.promise).mockReturnValueOnce(new Promise(() => {}));
  const first = runStockScanWithContinuation('first');
  void runStockScanWithContinuation('second');
  if (oldOutcome === 'success') old.resolve(result('old'));
  else old.reject(new Error('old failure'));
  const outcome = await first;
  expect(outcome.kind).toBe('obsolete'); expect(isStockManualScanCurrent(outcome)).toBe(false);
  expect(useScanStore.getState().scanState).toBe('SCANNING');
  expect(useScanStore.getState().stockScanResult).toBeNull();
  expect(useScanStore.getState().stockScanError).toBeNull();
  expect(useScanStore.getState().stockScanFeedback).toEqual({ error: null, notice: null });
});
it('does not replace newest result/request/feedback when an old success lands last', async () => {
  const old = deferred<StockScanResult>();
  (api.postStockScan as jest.Mock).mockReturnValueOnce(old.promise).mockResolvedValueOnce(result('new'));
  const first = runStockScanWithContinuation('first');
  const newest = await runStockScanWithContinuation('second');
  old.resolve(result('old'));
  expect((await first).kind).toBe('obsolete');
  expect(isStockManualScanCurrent(newest)).toBe(true);
  expect(useScanStore.getState().stockScanResult?.scan_id).toBe('new');
  expect(useScanStore.getState().stockScanRequest?.strategy).toBe('second');
  expect(useScanStore.getState().scanState).toBe('COMPLETED');
});
it('captures session intent once and refuses automatic saves with production unavailable authority', async () => {
  const scan = deferred<StockScanResult>();
  (api.postStockScan as jest.Mock).mockReturnValue(scan.promise);
  const save = jest.fn(); usePortfolioStore.setState({ addPosition: save });
  useScanStore.getState().setStockAfterScanIntent('AAPL', true);
  const run = runStockScanWithContinuation('strategy');
  useScanStore.getState().setStockAfterScanIntent('MSFT', true);
  scan.resolve(result('scan', [candidate('AAPL'), candidate('MSFT')]));
  expect((await run).kind).toBe('success');
  expect(save).not.toHaveBeenCalled();
  expect(useScanStore.getState().stockScanFeedback.notice).toContain('AAPL: Unvalidated');
  expect(useScanStore.getState().stockScanFeedback.notice).not.toContain('MSFT');
  expect(useScanStore.getState().stockAfterScanIntent).toEqual({ AAPL: true, MSFT: true });
});
it('finishes an already-started save, but supersession prevents a second save, feedback overwrite and navigation', async () => {
  // Only downstream continuation mechanics receive an availability stub;
  // production fail-closed execution is asserted in the unmocked case above.
  jest.spyOn(execution, 'stockExecutionBlock').mockReturnValue(null);
  const saved = deferred<{ ok: true; status: 'ok'; adjustedQty: number }>();
  const save = jest.fn().mockReturnValue(saved.promise); usePortfolioStore.setState({ addPosition: save });
  useScanStore.getState().setStockAfterScanIntent('AAPL', true);
  useScanStore.getState().setStockAfterScanIntent('MSFT', true);
  (api.postStockScan as jest.Mock).mockResolvedValueOnce(result('A', [candidate('AAPL'), candidate('MSFT')])).mockResolvedValueOnce(result('B'));
  const first = runStockScanWithContinuation('first');
  await Promise.resolve(); await Promise.resolve();
  expect(save).toHaveBeenCalledTimes(1);
  const second = await runStockScanWithContinuation('second');
  saved.resolve({ ok: true, status: 'ok', adjustedQty: 12 });
  const obsolete = await first;
  expect(obsolete.kind).toBe('obsolete'); expect(isStockManualScanCurrent(obsolete)).toBe(false);
  expect(isStockManualScanCurrent(second)).toBe(true);
  expect(save).toHaveBeenCalledTimes(1);
  expect(Object.values(useScanStore.getState().stockAfterScanOutcomes)).toEqual([expect.objectContaining({ symbol: 'AAPL', status: 'ok', adjustedQty: 12 })]);
  expect(useScanStore.getState().stockScanResult?.scan_id).toBe('B');
  expect(useScanStore.getState().stockScanRequest?.strategy).toBe('second');
  expect(useScanStore.getState().stockScanFeedback).toEqual({ error: null, notice: null });
});
it('uses pristine PASS-only levels and reports saved, queued, resized, rejected and skipped outcomes separately', async () => {
  jest.spyOn(execution, 'stockExecutionBlock').mockReturnValue(null);
  const save = jest.fn().mockResolvedValueOnce({ status: 'ok', adjustedQty: 12 }).mockResolvedValueOnce({ status: 'pending' }).mockResolvedValueOnce({ status: 'rejected', detail: 'risk limit' });
  usePortfolioStore.setState({ addPosition: save });
  for (const symbol of ['AAPL', 'MSFT', 'IBM', 'TSLA']) useScanStore.getState().setStockAfterScanIntent(symbol, true);
  (api.postStockScan as jest.Mock).mockResolvedValue(result('A', [candidate('AAPL'), candidate('MSFT'), candidate('IBM'), candidate('TSLA', 'CAUTION')]));
  expect((await runStockScanWithContinuation('strategy')).kind).toBe('success');
  expect(save).toHaveBeenCalledTimes(3);
  expect(save.mock.calls[0][0]).toMatchObject({ symbol: 'AAPL', contracts: 30, stop: 145 });
  expect(save.mock.calls[0][0].targets.map((t: { stockPrice: number }) => t.stockPrice)).toEqual([160, 165]);
  expect(useScanStore.getState().stockScanFeedback.error).toContain('IBM: risk limit');
  expect(useScanStore.getState().stockScanFeedback.notice).toMatch(/Queued.*MSFT.*Size reduced.*AAPL \(12 sh\).*Not fired.*TSLA/s);
});
